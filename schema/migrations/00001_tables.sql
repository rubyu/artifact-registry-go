CREATE TYPE __SCHEMA__.artifact_object_status_type AS ENUM (
    'uploading',
    'available',
    'upload_failed',
    'deleted',
    'delete_failed'
);

CREATE TYPE __SCHEMA__.artifact_publication_status_type AS ENUM (
    'staged',
    'committed',
    'discarding',
    'discarded',
    'aborted'
);

CREATE OR REPLACE FUNCTION __SCHEMA__.set_updated_at()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    NEW.updated_at = CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$;

CREATE TABLE __SCHEMA__.artifact_registry_objects (
    artifact_object_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    artifact_object_ref UUID NOT NULL DEFAULT uuidv7()
        CONSTRAINT artifact_registry_objects_artifact_object_ref_key UNIQUE,
    object_path TEXT NOT NULL UNIQUE,
    digest_value TEXT NOT NULL,
    size_bytes BIGINT NULL,
    status __SCHEMA__.artifact_object_status_type NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    uploaded_at TIMESTAMPTZ NULL,
    deleted_at TIMESTAMPTZ NULL,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT artifact_registry_objects_size_bytes_nonnegative_check
        CHECK (size_bytes IS NULL OR size_bytes >= 0),
    CONSTRAINT artifact_registry_objects_object_path_nonempty
        CHECK (object_path <> ''),
    CONSTRAINT artifact_registry_objects_status_lifecycle_check
        CHECK (
            (
              status = 'uploading'
              AND uploaded_at IS NULL
              AND deleted_at IS NULL
              AND size_bytes IS NULL
            )
            OR (
              status = 'available'
              AND uploaded_at IS NOT NULL
              AND deleted_at IS NULL
              AND size_bytes IS NOT NULL
              AND size_bytes >= 0
            )
            OR (
              status = 'upload_failed'
              AND uploaded_at IS NULL
              AND deleted_at IS NULL
              AND size_bytes IS NULL
            )
            OR (
              status = 'deleted'
              AND deleted_at IS NOT NULL
            )
            OR (
              status = 'delete_failed'
              AND deleted_at IS NULL
            )
        ),
    CONSTRAINT artifact_registry_objects_digest_value_hex_check
        CHECK (digest_value ~ '^[0-9a-f]{64}$')
);

CREATE TABLE __SCHEMA__.artifact_registry_publications (
    artifact_publication_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    artifact_ref UUID NOT NULL DEFAULT uuidv7()
        CONSTRAINT artifact_registry_publications_artifact_ref_key UNIQUE,
    artifact_object_ref UUID NOT NULL
        CONSTRAINT artifact_registry_publications_artifact_object_ref_key UNIQUE
        CONSTRAINT artifact_registry_publications_artifact_object_ref_fkey
        REFERENCES __SCHEMA__.artifact_registry_objects(artifact_object_ref),
    status __SCHEMA__.artifact_publication_status_type NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    committed_at TIMESTAMPTZ NULL,
    discard_requested_at TIMESTAMPTZ NULL,
    discarded_at TIMESTAMPTZ NULL,
    aborted_at TIMESTAMPTZ NULL,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT artifact_registry_publications_status_lifecycle_check
        CHECK (
            (
              status = 'staged'
              AND committed_at IS NULL
              AND discard_requested_at IS NULL
              AND discarded_at IS NULL
              AND aborted_at IS NULL
            )
            OR (
              status = 'committed'
              AND committed_at IS NOT NULL
              AND discard_requested_at IS NULL
              AND discarded_at IS NULL
              AND aborted_at IS NULL
            )
            OR (
              status = 'discarding'
              AND committed_at IS NOT NULL
              AND discard_requested_at IS NOT NULL
              AND discarded_at IS NULL
              AND aborted_at IS NULL
            )
            OR (
              status = 'discarded'
              AND committed_at IS NOT NULL
              AND discard_requested_at IS NOT NULL
              AND discarded_at IS NOT NULL
              AND aborted_at IS NULL
            )
            OR (
              status = 'aborted'
              AND committed_at IS NULL
              AND discard_requested_at IS NULL
              AND discarded_at IS NULL
              AND aborted_at IS NOT NULL
            )
        )
);

CREATE TRIGGER artifact_registry_objects_set_updated_at
BEFORE UPDATE ON __SCHEMA__.artifact_registry_objects
FOR EACH ROW EXECUTE FUNCTION __SCHEMA__.set_updated_at();

CREATE TRIGGER artifact_registry_publications_set_updated_at
BEFORE UPDATE ON __SCHEMA__.artifact_registry_publications
FOR EACH ROW EXECUTE FUNCTION __SCHEMA__.set_updated_at();

CREATE INDEX artifact_registry_objects_delete_failed_cleanup_idx
ON __SCHEMA__.artifact_registry_objects(updated_at, artifact_object_id)
WHERE status = 'delete_failed';

CREATE INDEX artifact_registry_publications_staged_cleanup_idx
ON __SCHEMA__.artifact_registry_publications(created_at, artifact_publication_id)
WHERE status = 'staged';

CREATE INDEX artifact_registry_publications_aborted_cleanup_idx
ON __SCHEMA__.artifact_registry_publications(aborted_at, artifact_publication_id)
WHERE status = 'aborted';

CREATE INDEX artifact_registry_publications_discarding_cleanup_idx
ON __SCHEMA__.artifact_registry_publications(discard_requested_at, artifact_publication_id)
WHERE status = 'discarding';
